package heart.cli.generate

import heart.cli.BadArguments
import java.io.PrintStream
import java.nio.file.Files
import java.nio.file.Path

/** The format `--format` asks for, kts unless it says yaml; a report shows only a Kotlin script beside its source. */
internal fun format(options: Map<String, String>, report: String?): String {
    val format = options["--format"] ?: "kts"
    if (format != "kts" && format != "yaml") throw BadArguments("--format is kts or yaml")
    if (format == "yaml" && report != null) {
        throw BadArguments("--report shows a Kotlin script: leave out --format yaml")
    }
    return format
}

/** `artie generate --format yaml`: [writer]'s script as data, and its lock file beside it, in [folder]. */
internal fun asData(writer: ScriptYaml, folder: Path, out: PrintStream) {
    val text = writer.write()
    val lock = LockWriter(writer.capture)
    Files.writeString(folder.resolve(writer.out), text)
    Files.writeString(folder.resolve(writer.pins), lock.write(writer.out, writer.capture.name))
    val kept = if (writer.kept > 0) ", ${count(writer.kept, "reason step")} kept" else ""
    out.println("wrote ${writer.out}: ${count(writer.reviews, "value")} to review$kept")
    out.println("wrote ${writer.pins}: ${count(lock.formCount, "form")} and ${count(lock.linkCount, "link")} pinned")
}

/**
 * The script a capture gives, as data (spec/PLAN-KEPT-SCRIPTS-AS-DATA.md, step 3): what [ScriptWriter] writes as
 * Kotlin, from the same walk, written as YAML in the vocabulary of spec/schemas/heart-script.draft.schema.json.
 * Every value read again is a reference: an input `${title}`, a member of a resource a step kept `${issue.number}`.
 */
class ScriptYaml(
    val capture: Capture,
    private val source: List<String>?,
    private val sourceName: String?,
    val out: String,
    val pins: String,
    private val options: ScriptWriter.Options = ScriptWriter.Options(),
) {
    private val bindings = Bindings(capture, source, options.asInputs.keys)
    private val walker = Walker(capture, bindings, WatchLines(capture), options) { names }

    /** The names the script knows, which a step's words may keep: its inputs and its variables. */
    private val names: Set<String>
        get() = capture.inputs.keys + options.asInputs.keys + bindings.variables.values.map { it.name }

    /** How many values the script marks for a person to review. */
    var reviews = 0
        private set

    /** How many acts the script checks after, by what they changed (Checks.kt). */
    private var checked = 0

    /** How many steps before a watch the model decides on every run: kept as reason steps, or as words. */
    var kept = 0
        private set

    /** Whether a list's members the run visited one by one are written as a whenever (Members.kt). */
    private var looped = false

    fun write(): String {
        capture.finished()
        // A goal run's watch, as the capture keeps it as data, after the steps before it; with --intents, in words.
        val watch = capture.watchScript?.let {
            capture.watchSteps ?: throw BadArguments("${capture.name} keeps its watch only as Kotlin: run it again")
        }.orEmpty().let { if (options.intents) inWords(it) as List<*> else it }
        val root = Node.of(capture).let { if (capture.source != null) Detours.trimmed(it, capture) else it }
        // Twice: the first pass meets every variable, so the second can read each from the resource it is kept in.
        steps(walker.walk(root))
        reviews = 0
        checked = 0
        val walked = walker.walk(root)
        kept = reasoned(walked)
        asked = asked(watch)
        val steps = steps(walked) + watch
        val kind = if (options.intents) "intent" else "kept"
        // A start the run was given as an input is that input, for wherever the next run is given.
        val start = capture.inputGiven(capture.entry)?.let { "\${$it}" } ?: capture.entry
        val document = linkedMapOf<String, Any?>("heart" to 1, "kind" to kind, "start" to start)
        val inputs = capture.inputs.mapValues { (name, input) -> declared(input, bindings.inputTypes[name]) }
        return (header() + YamlText.lines(document) + "" +
            (if (inputs.isEmpty()) emptyList() else YamlText.lines(mapOf("inputs" to inputs)) + "") +
            YamlText.lines(mapOf("steps" to steps))).joinToString("\n", postfix = "\n")
    }

    private fun header(): List<String> = listOfNotNull(
        "# Generated by artie generate from ${capture.name}" + (sourceName?.let { ", the run of $it" } ?: "") + ".",
        when {
            options.intents ->
                "# The run in words: its shape as it nested, each act said in words for the reasoner to choose on " +
                    "every run."
            kept == 0 && asked == 0 -> "# Every selection as that run made it, nested as it nested, with no model."
            kept == 0 ->
                "# Every selection as that run made it, nested as it nested; " +
                    "an act it left to the model stays in words."
            else -> "# Every selection as that run made it, nested as it nested; " +
                "where the reasoner chose a value, its reason step is kept."
        },
        "# The members of a list the run visited one by one are each acted on by what they offer (when-offered)."
            .takeIf { looped },
        "# What it was offered is pinned in $pins, held to before every act.",
        "# After an act, what it changed is checked: the run stops where that no longer holds.".takeIf { checked > 0 },
        calls(kept, asked)?.let { "# $it: artie run needs --reasoner." },
        "# A value marked \"review:\" holds a value the reasoner chose: check it before keeping the script."
            .takeIf { reviews > 0 },
        "#   artie run $out" + capture.inputs.filter { it.value["given"] == "given" }
            .entries.joinToString("") { (name, input) -> " $name=${shell(input["value"].toString())}" } +
            (if (kept > 0 || asked > 0) " --reasoner claude" else ""),
    )

    /** How many of the watch's steps the model decides each time one is reached: those it says are reasoned. */
    private var asked = 0

    /**
     * The steps of [block]: the resources it keeps, then the steps nested in it. An act that sends a value read from
     * the resource it acts on is written in a decide that keeps that resource again; kept there alone when nothing
     * before it opens a block that might read it.
     */
    private fun steps(block: Block): List<Map<String, Any?>> {
        // A list the run went through: a for-each over it, by the name its members are read by, with what each
        // offers, or its own list (Members.kt).
        fun over(loop: Loop): List<Map<String, Any?>> {
            val inside = loop.inner?.let(::over) ?: listOf(offered(loop.members))
            return listOf(linkedMapOf("for-each" to loop.name, "then" to inside))
        }
        loop(block) { capture.inputGiven(it) != null }?.let { loop ->
            return keeps(block) + bindings.within(loop.scope) { over(loop) }
        }
        val decided = decided(block, capture)
        val inside = decided.values.flatten().toSet().takeIf { movable(block, decided.keys) }.orEmpty()
        val made = block.statements.map { walked ->
            val named = scenarioOf(capture, walked)?.takeIf { it != inScenario }
            val outer = inScenario
            inScenario = named ?: outer
            val steps = decided[walked]?.let { kept -> listOf(decide(kept, step(walked))) } ?: step(walked)
            inScenario = outer
            named to steps
        }
        return keeps(block).filter { it["keep-as"] !in inside } + scenarios(made)
    }

    /** The scenario the steps being written are in, so a scenario's own acts are not wrapped in it again. */
    private var inScenario: String? = null

    /**
     * [members] of one list, each acted on by the first of the run's acts it offers now, in the order the run first
     * made them, else noted; the step's words kept for a member that offers an act the run never met.
     */
    private fun offered(members: List<Walked.Selection>): Map<String, Any?> {
        looped = true
        val acts = cases(members).map { case ->
            val act = act(case.step)
            val then = (act["then"] as? List<*>).orEmpty() + (if (case.step.opens) steps(case.block) else emptyList())
            act + listOfNotNull(("then" to then).takeIf { case.step.opens || then.isNotEmpty() })
        }
        val offered = linkedMapOf<String, Any?>("when-offered" to acts)
        words(capture, members.first().step, names, emptyList())?.let { it.fromIntent ?: it.intent }
            ?.let { offered["intent"] = text(it) }
        offered["otherwise"] = listOf(mapOf("note" to "none of these acts is offered here"))
        return offered
    }

    private fun keeps(block: Block): List<Map<String, Any?>> =
        (block.keeps.map { it.keptAs }.distinct() + listOfNotNull(block.watched)).map { mapOf("keep-as" to it) }

    private fun step(walked: Walked): List<Map<String, Any?>> = when (walked) {
        is Walked.Selection -> selection(walked)
        is Walked.Sync -> listOf(mapOf("sync" to true))
        // A Verify: fact read by name is kept as written, the name read again (goal-scenarios.feature).
        is Walked.Waits -> capture.marks(walked.step)["facts"]?.let { listOf(mapOf("check" to it)) }
            ?: listOf(readAgain(bindings, capture, waited(walked.step)))
        // Another party's entry, or a reply waited on, as the goal's step opened it (goal-rise.feature).
        is Walked.Scope -> listOf(
            if (walked.kind == "enter") {
                linkedMapOf("enter" to walked.value, "steps" to steps(walked.block))
            } else {
                linkedMapOf("once-answered" to linkedMapOf("reply" to walked.value, "steps" to steps(walked.block)))
            },
        )
    }

    /**
     * An act or a follow, its words, and its block: begun with a read again of a resource it just made. A reason step
     * kept is its words, marked reasoned; with --intents, every act and follow is its words alone.
     */
    private fun selection(selection: Walked.Selection): List<Map<String, Any?>> {
        val step = selection.step
        val made = linkedMapOf<String, Any?>()
        when (selection.call) {
            Call.Reasoned -> {
                // Its slots an earlier answer filled are read from what that step kept, as a Kotlin script's are.
                bindings.kept(step)
                made["intent"] = text(reasonedWords(capture, step))
                made["reasoned"] = true
            }
            is Call.Words -> words(capture, step, names, emptyList())?.let { made.putAll(said(it)) }
            Call.Follow -> {
                made["follow"] = step.relation
                // A title the run was given as an input is followed by that input, for whatever it is next time.
                step.params["title"]?.toString()?.let { made["title"] = capture.inputGiven(it)?.let(::reference) ?: it }
                words(capture, step, names, emptyList())?.let { made.putAll(said(it)) }
            }
            Call.Act -> made.putAll(act(step))
        }
        // As of a version a step named, and the refusal it expected (goal-scenarios.feature).
        val marks = capture.marks(step)
        made.putAll(versioned(marks))
        // An act that asked to be told, on a reply the host kept by its step's name (goal-rise.feature): the reply's
        // envelope is the ask's to make, and what it led to is held after it.
        val reply = marks["ask"]?.toString()
        // What the step named, kept by that name where a later step acts as of it or reads it.
        val named = marks["as"]?.toString()?.takeIf { it in readByName }?.let { mapOf("keep-as" to it) }
        return when {
            reply != null -> asked(made, reply) + steps(selection.block)
            // A step that opens none holds no block: what it led to is kept where it stands.
            !step.opens -> listOf(made) +
                (listOfNotNull(named) + selection.block.keeps.map { mapOf("keep-as" to it.keptAs) }).distinct()
            else -> {
                // A resource made new is read again first; then what the act changed is checked, then the steps in it.
                made["then"] = (listOfNotNull(mapOf("sync" to true).takeIf { selection.fresh }, named) +
                    (made["then"] as? List<*>).orEmpty() + steps(selection.block)).distinct()
                listOf(made)
            }
        }
    }

    /** The names a later step acts as of, or a Verify: fact reads: each kept where its step named it. */
    private val readByName: Set<String> by lazy { namesRead(capture) }

    /** An act as the run made it: its relation, each value it sent, and its words. */
    private fun act(step: Step): Map<String, Any?> {
        val arguments = bindings.arguments(step)
        reviews += arguments.count { it.review != null }
        val act = linkedMapOf<String, Any?>("act" to step.relation)
        if (arguments.isNotEmpty()) act["fields"] = arguments.associate { it.field to noted(it) }
        words(capture, step, names, arguments, bindings.titles(capture, step))?.let { act.putAll(said(it)) }
        val sent = arguments.associate { it.field to it.value }
        checked(capture, step, sent.keys).takeIf { it.isNotEmpty() }?.let { facts ->
            val check = facts.map { mapOf("field" to it.field, "is" to if (it.sent) sent[it.field] else it.value) }
            act["then"] = listOf(mapOf("check" to check))
            checked++
        }
        return act
    }

    /** [words] as data, each slot the reference that reads it again. */
    private fun said(words: Words): Map<String, Any?> = listOfNotNull(
        words.intent?.let { "intent" to text(it) },
        words.inferred?.let { "inferred" to text(it) },
        words.fromIntent?.let { "from-intent" to text(it) },
    ).toMap()

    /** Words with a script's slots, `$name` or `${'$'}{name}`, each the reference that reads it; a dollar a dollar. */
    private fun text(words: String): String = SLOT.replace(words) { slot ->
        val name = slot.groupValues[1].ifEmpty { slot.groupValues[2] }
        if (name.isEmpty()) "$" else bindings.referenceOf(name)
    }

    private companion object {
        val SLOT = Regex("""\$\{'\$'}|\$\{([^}]*)}|\$([A-Za-z_][A-Za-z0-9_]*)""")
    }
}

/** An input as the capture kept its declaration: nothing for a required one, else its default and question. */
/** [argument]'s value, with its review note when a person should look at it. */
private fun noted(argument: Argument): Any? =
    argument.review?.let { Noted(argument.value, "review: $it") } ?: argument.value

private fun declared(input: Map<*, *>, type: String?): Map<String, Any?>? {
    val default = input["now"]?.let { mapOf("now" to it.toString()) } ?: input["default"]?.toString()
    val declared = listOfNotNull(
        default?.let { "default" to it },
        input["question"]?.let { "question" to it },
        type?.let { "type" to it },
    )
    return declared.toMap().takeIf { it.isNotEmpty() }
}

/** How many steps in [data], a watch's, however deep, the model decides each time: its words with no relation. */
private fun asked(data: Any?): Int = when (data) {
    is Map<*, *> -> (if (worded(data) && "act" !in data && "follow" !in data) 1 else 0) +
        data.values.sumOf { asked(it) }
    is List<*> -> data.sumOf { asked(it) }
    else -> 0
}

/** [data], a watch's, with each act that keeps its words written as them alone (--intents). */
private fun inWords(data: Any?): Any? = when (data) {
    is Map<*, *> -> data.filterKeys { !(worded(data) && (it == "act" || it == "fields")) }
        .mapValues { inWords(it.value) }
    is List<*> -> data.map(::inWords)
    else -> data
}

private fun worded(step: Map<*, *>): Boolean = "intent" in step || "inferred" in step

/**
 * A wait or a check as data, from what the capture kept of it, never from a script's Kotlin: until a relation is
 * offered; each fact checked, a member equal to a value or holding one.
 */
internal fun waited(step: Step): Map<String, Any?> {
    if (step.say == "until") {
        val relation = OFFERS.matchEntire(step.waitedFor.orEmpty().trim())?.groupValues?.get(1)
            ?: throw BadArguments("step ${step.number}: a wait for ${step.waitedFor} can't be data yet")
        return mapOf("until" to mapOf("offered" to relation))
    }
    val facts = step.params["facts"].list().map { it.map() }
    if (facts.isEmpty()) throw BadArguments("step ${step.number}: a check the capture can't write back")
    return mapOf("check" to facts.map { fact(step, it) })
}

/** [wait], with each text a check holds read again where it holds a value an earlier answer gave. */
private fun readAgain(bindings: Bindings, capture: Capture, wait: Map<String, Any?>): Map<String, Any?> {
    val facts = wait["check"] as? List<*> ?: return wait
    return mapOf(
        "check" to facts.map { fact ->
            (fact as Map<*, *>).entries.associate { (key, value) ->
                key.toString() to if (key != "field" && value is String) bindings.readAgain(capture, value) else value
            }
        },
    )
}

private fun fact(step: Step, fact: Map<*, *>): Map<String, Any?> {
    val test = fact["test"].toString()
    val key = when (test.substringBefore(' ')) {
        "eq" -> "is"
        "has" -> "has"
        else -> throw BadArguments("step ${step.number}: a check \"$test\" can't be data yet")
    }
    val argument = test.substringAfter(' ', "")
    val value: Any? = when {
        argument == "null" -> null
        argument == "true" || argument == "false" -> argument.toBoolean()
        else -> argument.toLongOrNull() ?: argument.toDoubleOrNull() ?: argument
    }
    return mapOf("field" to fact["member"].toString(), key to value)
}

private val OFFERS = Regex("""offers\("([^"]+)"\)""")

package heart.cli.generate

import heart.script.kotlinString

/**
 * The script a capture gives (spec/PLAN-SCRIPT-GENERATOR.md): its inputs, then every selection the run made,
 * nested as the run nested them, each variable read in the block of the step that brought its value in. With the
 * run's own script ([source]), inputs, waits and checks are copied from its lines; without, from the capture.
 */
class ScriptWriter(
    private val capture: Capture,
    private val source: List<String>?,
    private val sourceName: String?,
    private val out: String,
    private val pins: String,
    private val options: Options = Options(),
) {
    /**
     * `--keep-reason`; `--inputs` with each named field's text, the run's, as its default; and `--intents`, every
     * act and follow written as its words alone, for the reasoner to choose on every run.
     */
    class Options(
        val keepReason: Boolean = false,
        val asInputs: Map<String, String> = emptyMap(),
        val intents: Boolean = false,
    )

    /** How each value and line was derived, noted as the script is written. */
    val derivations = Derivations(source)
    private val why = Why(derivations)
    private val bindings = Bindings(capture, source, options.asInputs.keys, derivations)
    private val watch = WatchLines(capture)
    private val walker = Walker(capture, bindings, watch, options) { names }

    /** How many values the script marks for a person to review. */
    var reviews = 0
        private set

    /** How many reason steps the script keeps (`--keep-reason`). */
    var kept = 0
        private set

    /** How many acts the script checks after, by what they changed (Checked.kt). */
    private var checked = 0

    /** Whether a list's members the run visited one by one are written as a whenever (Members.kt). */
    private var looped = false

    fun write(): String {
        capture.finished()
        // A goal run's detours are left out: the script does only what the goal needed.
        val root = Node.of(capture).let { if (capture.source != null) Detours.trimmed(it, capture) else it }
        // Twice: the first pass meets every variable, so the second can read each in the block it belongs to.
        block(walker.walk(root), 1)
        reviews = 0
        checked = 0
        derivations.clear()
        val walked = walker.walk(root)
        kept = reasoned(walked)
        val body = block(walked, 1)
        val entry = capture.steps.first()
        val heart = "heart(${KotlinText.quoted(capture.entry)}) {"
        return derivations.strip(
            buildString {
                header().forEach { appendLine(it) }
                watch.imports().forEach { appendLine(it) }
                inputs().forEach { appendLine(it) }
                appendLine()
                appendLine(derivations.anchor("${entry.number}", entry.line, heart))
                bindings.variables.values.forEach {
                    val declared = derivations.lines(Regex("^\\s*va[rl]\\s+${it.name}\\b"))
                    val line = why.mark(why.answer(it, null), it.declared, listOf(declared))
                    val from = if (it.looped) "each ${it.keptAs}'s" else "step ${it.step}'s"
                    appendLine("$INDENT$line // $from ${it.pointer}")
                }
                if (bindings.variables.isNotEmpty()) appendLine()
                body.forEach { appendLine(it) }
                // A goal run's watch, as its decisions amount to, after the steps before it.
                watch.lines(1, options.intents).forEach { appendLine(it) }
                appendLine("}")
            },
        )
    }

    private fun header(): List<String> = listOfNotNull(
        "// Generated by artie generate from ${capture.name}" + (sourceName?.let { ", the run of $it" } ?: "") + ".",
        if (options.intents) {
            "// The run in words: its shape as it nested, each act said in words for the reasoner to choose on " +
                "every run."
        } else if (kept == 0 && asked == 0) {
            "// Every selection as that run made it, nested as it nested, with no model."
        } else if (kept == 0) {
            "// Every selection as that run made it, nested as it nested; an act it left to the model stays in words."
        } else {
            "// Every selection as that run made it, nested as it nested; " +
                "where the reasoner chose a value, its reason step is kept."
        },
        "// The members of a list the run visited one by one are each acted on by what they offer (whenOffered)."
            .takeIf { looped },
        "// What it was offered is pinned in $pins, held to before every act.",
        "// After an act, what it changed is checked: the run stops where that no longer holds.".takeIf { checked > 0 },
        // How often the script calls the model, said where a person sees it first.
        calls(kept, asked)?.let { "// $it: artie run needs --reasoner." },
        ("// A line marked \"review:\" holds a value the reasoner chose: check it before keeping the script.")
            .takeIf { reviews > 0 },
        "//   artie run $out" + capture.inputs.filter { it.value["given"] == "given" }
            .entries.joinToString("") { (name, input) -> " $name=${shell(input["value"].toString())}" } +
            (if (kept > 0 || asked > 0) " --reasoner claude" else ""),
    )

    /** The watch's acts written as words alone, each asked of the model whenever the watch reaches it. */
    private val asked: Int get() = watch.asked(options.intents)

    /** The inputs, each as the run's script declared it, else as the capture kept it; the first begins a row. */
    private fun inputs(): List<String> {
        val declared = capture.inputs.mapValues { (name, _) ->
            derivations.lines(Regex("""^\s*val\s+$name\s+by\s+input\(""")).firstOrNull()
        }
        val lines = capture.inputs.map { (name, input) ->
            val at = declared[name]
            why.mark(why.input(name), at?.text ?: declared(name, input), listOfNotNull(at?.let(::listOf)))
        } + options.asInputs.map { (name, text) ->
            why.mark(why.input(name, text), "val $name by input(default = ${KotlinText.quoted(text)})")
        }
        val first = declared.values.mapNotNull { it?.line }.minOrNull()
        return lines.mapIndexed { i, line -> if (i == 0) derivations.anchor("inputs", first, line) else line }
    }

    /**
     * The statements of [block], at [depth]: what it keeps, then the steps nested in it. An act that sends a value read
     * from the resource it acts on is in a decide that keeps that resource again (Decided.kt), as the script held as
     * data has it; kept there alone when nothing before it opens a block that might read it.
     */
    private fun block(block: Block, depth: Int): List<String> {
        val pad = INDENT.repeat(depth)
        val watched = block.watched?.let { listOf("${pad}keepAs(\"$it\")") }.orEmpty()
        // A list the run went through: a whenever, each member acted on by what it offers, or its own list in turn
        // (Members.kt), as the script held as data writes it.
        fun over(loop: Loop, at: Int): List<String> {
            val padded = INDENT.repeat(at)
            val opened = "${padded}each(${KotlinText.quoted(loop.name)}) {"
            loop.inner?.let { return listOf(opened) + over(it, at + 1) + "$padded}" }
            val words = words(capture, loop.members.first().step, names, emptyList())
                ?.let { it.fromIntent ?: it.intent }
            val cases = cases(loop.members).map { it.step.relation.orEmpty() to statement(it, at + CASE_DEPTH) }
            return overMembers(at, loop.name, words, cases)
        }
        loop(block) { capture.inputGiven(it) != null }?.let { loop ->
            looped = true
            return reads(block.keeps, depth) + watched + bindings.within(loop.scope) { over(loop, depth) }
        }
        val decided = decided(block, capture)
        val inside = decided.values.flatten().toSet().takeIf { movable(block, decided.keys) }.orEmpty()
        return reads(block.keeps.filter { it.keptAs !in inside }, depth) + watched +
            block.statements.flatMap { walked ->
                val kept = decided[walked] ?: return@flatMap statement(walked, depth)
                listOf("${pad}decide {") + kept.map { "$pad${INDENT}keepAs(\"$it\")" } + statement(walked, depth + 1) +
                    "$pad}"
            }
    }

    /** The resources [keeps] names, each kept by the name its values are read by, once however many it has. */
    private fun reads(keeps: List<Variable>, depth: Int): List<String> = keeps.map {
        val set = derivations.lines(Regex("^\\s*(?:${it.name}\\s*=[^=]|keepAs\\(\"${it.keptAs}\"\\))"))
        INDENT.repeat(depth) + why.mark(why.answer(it, null), "keepAs(\"${it.keptAs}\")", listOf(set))
    }

    /** The lines of [walked], the first of which begins its row. */
    private fun statement(walked: Walked, depth: Int): List<String> {
        val step = walked.step
        val pad = INDENT.repeat(depth)
        val lines = when (walked) {
            is Walked.Selection -> selection(walked, depth)
            is Walked.Sync -> listOf("${pad}sync()")
            is Walked.Waits -> waits(step, pad)
            // `enter("…") { … }` or `onceAnswered("…") { … }`, as the goal's step opened it (goal-rise.feature).
            is Walked.Scope -> listOf("$pad${KOTLIN_SCOPES.getValue(walked.kind)}(\"${walked.value}\") {") +
                block(walked.block, depth + 1) + "$pad}"
        }
        return lines.mapIndexed { i, line ->
            if (i == 0) derivations.anchor("${step.number}", step.line, line) else line
        }
    }

    /** A wait or a check, each line where the run's script wrote it. */
    private fun waits(step: Step, pad: String): List<String> = Waits.of(step, source).mapIndexed { i, line ->
        val at = (step.line ?: 0) + i
        val copied = source?.getOrNull(at - 1)?.let { Span(at, it.length - it.trimStart().length + 1, it.trim()) }
        pad + why.mark(why.copied(step.say, source != null), line, listOfNotNull(copied?.let(::listOf)))
    }

    /** [walked] as Kotlin: its call, then its block, or what it led to kept where it stands when it opens none. */
    private fun selection(walked: Walked.Selection, depth: Int): List<String> {
        val step = walked.step
        val pad = INDENT.repeat(depth)
        var facts: String? = null
        val call = when (val how = walked.call) {
            Call.Reasoned -> listOf(pad + bindings.kept(step))
            is Call.Words -> listOf("${pad}act(${how.words})")
            Call.Follow -> listOf(pad + follow(step))
            Call.Act -> act(step, pad).let { (lines, checked) -> facts = checked; lines }
        }
        // A resource made new is read again first; then what the act changed is checked, then the steps in it.
        val checks = listOfNotNull(facts?.let { "${INDENT.repeat(depth + 1)}check($it)" })
        val inner = listOfNotNull("${INDENT.repeat(depth + 1)}sync()".takeIf { walked.fresh }) + checks +
            block(walked.block, depth + 1)
        return when {
            !step.opens && checks.isEmpty() -> call + reads(walked.block.keeps, depth)
            !step.opens -> call.dropLast(1) + (call.last() + " {") + checks + "$pad}" + reads(walked.block.keeps, depth)
            inner.isEmpty() -> call.dropLast(1) + (call.last() + " {}")
            else -> call.dropLast(1) + (call.last() + " {") + inner + "$pad}"
        }
    }

    private fun follow(step: Step): String {
        // A title the run was given as an input is followed by that input, for whatever it is next time.
        val title = step.params["title"]?.toString()
            ?.let { ", ${capture.inputGiven(it) ?: KotlinText.quoted(it)}" }.orEmpty()
        val said = said(capture, step, names, emptyList())?.let { ", $it" }.orEmpty()
        return "follow(${why.relation(step, source)}$title$said)"
    }

    /** The names the script knows, which a step's intent may keep: its inputs and its variables. */
    private val names: Set<String>
        get() = capture.inputs.keys + options.asInputs.keys + bindings.variables.values.map { it.name }

    /**
     * `act("rel", "field" to value, …, intent = "…")` on one line; when a value is marked or the line is long, its
     * values in a block, one a line: `act("rel", intent = "…", fields = { "field" to value })`. With it, the facts
     * checked after it (Checked.kt), `"status" eq "on notice"`, a member it sent by the expression it sends.
     */
    private fun act(step: Step, pad: String): Pair<List<String>, String?> {
        val relation = why.relation(step, source)
        val arguments = bindings.arguments(step)
        val intent = said(capture, step, names, arguments, bindings.titles(capture, step))
        reviews += arguments.count { it.review != null }
        val sent = arguments.associate { it.field to it.expression }
        val facts = checked(capture, step, sent.keys).takeIf { it.isNotEmpty() }?.joinToString(", ") {
            val value = (it.value as? String)?.let(KotlinText::quoted) ?: "${it.value}"
            KotlinText.quoted(it.field) + " eq " + if (it.sent) sent.getValue(it.field) else value
        }?.also { checked++ }
        val oneLine = "${pad}act(" + (listOf(relation) + arguments.map { "\"${it.field}\" to ${it.expression}" } +
            listOfNotNull(intent)).joinToString(", ") + ")"
        // An act that sends nothing has no values to set out a line each: one line, however long.
        val long = arguments.isNotEmpty() &&
            (arguments.any { it.review != null } || Derivations.visible(oneLine) > WIDTH)
        if (!long) return listOf(oneLine) to facts
        val head = "${pad}act(" + (listOf(relation) + listOfNotNull(intent) + "fields = {").joinToString(", ")
        return listOf(head) + arguments.map {
            "$pad$INDENT\"${it.field}\" to ${it.expression}" + (it.review?.let { why -> " // review: $why" } ?: "")
        } + "$pad})" to facts
    }

    private companion object {
        const val INDENT = "    "

        /** Each scope a goal's step opens, as the Kotlin DSL calls it. */
        val KOTLIN_SCOPES = mapOf("enter" to "enter", "once-answered" to "onceAnswered")
        const val WIDTH = 120
    }
}

/** A capture's nodes walked (Walk.kt): what each step is in the script, decided once, before it is written. */
internal class Walker(
    private val capture: Capture,
    private val bindings: Bindings,
    private val watch: WatchLines,
    private val options: ScriptWriter.Options,
    /** The names the script knows, which a step's intent may keep. */
    private val names: () -> Set<String>,
) {
    /** [node]'s block, walked: the resources it keeps, then the steps nested in it. */
    fun walk(node: Node): Block {
        // A loop's member is kept by the loop, not by the visit the value was read at.
        val keeps = bindings.variables.values.filter { it.step == node.step.number && !it.looped }
            .distinctBy { it.keptAs }
        // A resource the watch reads again and a value read from it are kept once, by the one name.
        val watched = watch.kept(node.step).takeIf { keeps.isEmpty() }
        return Block(keeps, watched, node.children.mapNotNull(::walked), node.step.items, node.step.relation)
    }

    /** What [node]'s step is in the script: a selection, a sync, a wait or a check; null for none of these. */
    private fun walked(node: Node): Walked? {
        val step = node.step
        // A block a goal's step opened by its words: another party's entry, or a reply waited on (goal-rise.feature).
        val scope = capture.marks(step).let { marks -> SCOPES.firstOrNull { it in marks }?.let { it to marks[it] } }
        return when {
            // A wait's own reads again are the scope's, not the script's: its block keeps what was done in it.
            scope != null -> Walked.Scope(step, scope.first, scope.second.toString(), walk(node).withoutSyncs())
            step.relation != null -> selection(node)
            step.say == "sync" -> Walked.Sync(step)
            step.say == "until" || step.say == "check" -> Walked.Waits(step)
            else -> null
        }
    }

    private fun selection(node: Node): Walked.Selection {
        val step = node.step
        val keep = keeps(capture, step, options.keepReason)
        // --intents: the act in its words alone, a person's or a model's, for the reasoner to choose each time.
        val words = said(capture, step, names(), emptyList()).takeIf { options.intents && !keep }
        val call = when {
            keep -> Call.Reasoned
            // Its words still read what an earlier answer gave from where that answer is kept.
            words != null -> Call.Words(words).also { bindings.slotsRead(capture, step) }
            step.follows -> Call.Follow
            else -> Call.Act
        }
        // A resource just made may change on its own (GitHub works out a new pull request's mergeability): an
        // act in its block reads it again first, as a reasoned run did, or its validator is stale.
        val fresh = step.outcome == "new resource" && node.children.any { acts(it.step) }
        return Walked.Selection(step, call, fresh, walk(node))
    }
}

/** How many selections in [block], however deep, the reasoner makes on every run: kept as reason steps, or words. */
internal fun reasoned(block: Block): Int = block.statements.sumOf { walked ->
    val selection = walked as? Walked.Selection
    val asked = selection?.call.let { it == Call.Reasoned || it is Call.Words }
    (if (asked) 1 else 0) + (selection?.let { reasoned(it.block) } ?: 0)
}

/**
 * A goal run's ([goal]) intent [words], each value an earlier answer gave put as the variable the script reads it
 * from, so the words say what the script does on another run: "get issue ${'$'}{number}", not the number it held.
 */
private fun spoken(words: String, named: List<Pair<String, String>>, goal: Boolean): String {
    if (!goal) return words
    return named.filter { it.first.isNotEmpty() }.fold(words) { said, (text, name) ->
        Regex("(?<![\\w$])(?<!\\d\\.)${Regex.escape(text)}(?![\\w])(?!\\.\\d)").replace(said) { "\${$name}" }
    }
}

/**
 * What [step] of [capture] was for, as its act or follow says it: `intent = "…"`, a person's words, those of the goal
 * step whose job it did, or the script's; else `inferred = "…"`, the words a model chose it by, each value an
 * earlier answer gave put as the variable of [names] the script reads it from ([arguments]). Null when there are none.
 */
private fun said(
    capture: Capture,
    step: Step,
    names: Set<String>,
    arguments: List<Argument>,
    titles: Map<String, String> = emptyMap(),
): String? {
    val words = words(capture, step, names, arguments, titles) ?: return null
    val from = words.fromIntent?.let { ", fromIntent = " + kotlinString(it) }.orEmpty()
    return words.intent?.let { "intent = " + kotlinString(it) }
        ?: ("inferred = " + kotlinString(words.inferred.orEmpty()) + from)
}

/**
 * What a step was for, in words, each with the slots a script writes (`$title`, `${'$'}{issue}`): a person's
 * ([intent]), else a model's ([inferred]) with the person's it serves ([fromIntent]).
 */
internal class Words(val intent: String?, val inferred: String?, val fromIntent: String?)

/**
 * [step]'s words, as [said] writes them: null when there are none. Inside a loop, a member's title a model's words
 * name is the variable of [titles] that reads it from whichever member the loop is at.
 */
internal fun words(
    capture: Capture,
    step: Step,
    names: Set<String>,
    arguments: List<Argument>,
    titles: Map<String, String> = emptyMap(),
): Words? {
    val goal = capture.source != null
    // A goal run's acts are the planner's, each in its words, but the act that did a step's job has the step's;
    // a script's are its author's, but where it said they were a model's.
    val person = if (goal) {
        capture.marks(step)["intent"]?.toString()
    } else {
        intent(step, names).takeIf { step.inferred == null }
    }
    val inferred = if (goal) intent(step, names) else step.inferred
    // The person's words a model's serve: a step that names no act, or an act on the way to a step's job.
    val from = if (goal) capture.marks(step)["fromIntent"]?.toString() else step.fromIntent
    return when {
        person != null -> Words(person, null, null)
        inferred != null ->
            Words(null, spoken(inferred, arguments.flatMap { it.named.toList() } + titles.toList(), goal), from)
        else -> null
    }
}

/**
 * Whether [step] of [capture] stays a reason step: a goal step marked reasoned, whatever its values looked like, and
 * with --keep-reason ([keepReason]) one where the reasoner chose a value its words don't give.
 */
private fun keeps(capture: Capture, step: Step, keepReason: Boolean): Boolean = step.mode == "intent" &&
    (keepReason && step.judged || capture.marks(step)["reasoned"] != null)

/**
 * Which parts of a script call the model, and how often: [kept] steps on every run, [asked] acts in the watch each
 * time one is reached. Null when none do.
 */
internal fun calls(kept: Int, asked: Int): String? {
    val steps = (if (kept == 1) "1 step calls" else "$kept steps call") + " the model on every run"
    val acts = if (asked == 1) "1 act in the watch" else "$asked acts in the watch"
    return when {
        kept > 0 && asked > 0 -> "$steps, and $acts each time one is reached"
        kept > 0 -> steps
        asked > 0 -> "$acts ${if (asked == 1) "calls" else "call"} the model each time one is reached"
        else -> null
    }
}

/** Whether [step] acts: a form, not a link, and not a read. */
private fun acts(step: Step): Boolean = !step.follows && (step.relation != null || step.mode == "intent") &&
    step.chose["method"]?.toString()?.uppercase() != "GET"

/** [value] as one shell word. */
internal fun shell(value: String): String = if (value.matches(Regex("[A-Za-z0-9._/:@=+-]+"))) value else
    "'" + value.replace("'", "'\\''") + "'"

/** An input as the capture kept its declaration: required, or with its default or its question. */
private fun declared(name: String, input: Map<*, *>): String {
    // A default made fresh each run is made fresh in the script too: the time now, by its pattern.
    val now = input["now"]?.let {
        "default = java.time.LocalDateTime.now().format(java.time.format.DateTimeFormatter.ofPattern(" +
            "${KotlinText.quoted(it.toString())}))"
    }
    val named = listOfNotNull(
        now ?: input["default"]?.let { "default = ${KotlinText.quoted(it.toString())}" },
        input["question"]?.let { "question = ${KotlinText.quoted(it.toString())}" },
    )
    return "val $name by input(${named.joinToString(", ")})"
}

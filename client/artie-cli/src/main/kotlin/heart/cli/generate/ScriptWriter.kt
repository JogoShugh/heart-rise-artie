package heart.cli.generate

/**
 * The script a capture gives (spec/PLAN-SCRIPT-GENERATOR.md): its inputs, then every selection the run made,
 * nested as the run nested them, each variable read in the block of the step that brought its value in. With the
 * run's own script ([source]), inputs, waits and checks are copied from its lines; without, from the capture.
 */
class ScriptWriter(
    private val capture: Capture,
    private val source: List<String>?,
    private val sourceName: String?,
    private val out: String,
    private val pins: String,
    private val options: Options = Options(),
) {
    /** `--keep-reason`, and `--inputs` with each named field's text, the run's, as its default. */
    class Options(val keepReason: Boolean = false, val asInputs: Map<String, String> = emptyMap())

    private val bindings = Bindings(capture, source, options.asInputs.keys)

    /** How many values the script marks for a person to review. */
    var reviews = 0
        private set

    /** How many reason steps the script keeps (`--keep-reason`). */
    var kept = 0
        private set

    fun write(): String {
        capture.finished()
        val root = Node.of(capture)
        // Twice: the first pass meets every variable, so the second can read each in the block it belongs to.
        block(root, 1)
        reviews = 0
        kept = 0
        val body = block(root, 1)
        return buildString {
            header().forEach { appendLine(it) }
            inputs().forEach { appendLine(it) }
            appendLine()
            appendLine("heart(${KotlinText.quoted(capture.entry)}) {")
            bindings.variables.values.forEach {
                appendLine("${INDENT}var ${it.name} = ${it.kind.initial} // step ${it.step}'s ${it.pointer}")
            }
            if (bindings.variables.isNotEmpty()) appendLine()
            body.forEach { appendLine(it) }
            appendLine("}")
        }
    }

    private fun header(): List<String> = listOfNotNull(
        "// Generated by artie generate from ${capture.name}" + (sourceName?.let { ", the run of $it" } ?: "") + ".",
        if (kept == 0) {
            "// Every selection as that run made it, nested as it nested, with no model."
        } else {
            "// Every selection as that run made it, nested as it nested; " +
                "where the reasoner chose a value, its reason step is kept."
        },
        "// What it was offered is pinned in $pins, held to before every act.",
        ("// A line marked \"review:\" holds a value the reasoner chose: check it before keeping the script.")
            .takeIf { reviews > 0 },
        "//   artie run $out" + capture.inputs.filter { it.value["given"] == "given" }
            .entries.joinToString("") { (name, input) -> " $name=${shell(input["value"].toString())}" } +
            (if (kept > 0) " --reasoner claude" else ""),
    )

    private fun inputs(): List<String> = capture.inputs.map { (name, input) ->
        source?.firstOrNull { Regex("""^\s*val\s+$name\s+by\s+input\(""").containsMatchIn(it) }?.trim()
            ?: declared(name, input)
    } + options.asInputs.map { (name, text) -> "val $name by input(default = ${KotlinText.quoted(text)})" }

    /** The statements of [node]'s block, at [depth]: what it reads, then the steps nested in it. */
    private fun block(node: Node, depth: Int): List<String> =
        reads(node.step.number, depth) + node.children.flatMap { statement(it, depth) }

    private fun reads(step: Int, depth: Int): List<String> =
        bindings.variables.values.filter { it.step == step }.map { "${INDENT.repeat(depth)}${it.name} = ${it.read}" }

    private fun statement(node: Node, depth: Int): List<String> {
        val step = node.step
        val pad = INDENT.repeat(depth)
        return when {
            step.relation != null -> selection(node, depth)
            step.say == "sync" -> listOf("${pad}sync()")
            step.say == "until" || step.say == "check" -> Waits.of(step, source).map { pad + it }
            else -> emptyList()
        }
    }

    private fun selection(node: Node, depth: Int): List<String> {
        val step = node.step
        val pad = INDENT.repeat(depth)
        val keep = options.keepReason && step.mode == "intent" && step.judged
        if (keep) kept++
        val call = when {
            keep -> listOf(pad + bindings.kept(step))
            step.follows -> listOf(pad + follow(step))
            else -> act(step, pad)
        }
        val inner = block(node, depth + 1)
        return when {
            !step.opens -> call + reads(step.number, depth)
            inner.isEmpty() -> call.dropLast(1) + (call.last() + " {}")
            else -> call.dropLast(1) + (call.last() + " {") + inner + "$pad}"
        }
    }

    private fun follow(step: Step): String {
        val title = step.params["title"]?.let { ", ${KotlinText.quoted(it.toString())}" }.orEmpty()
        return "follow(${KotlinText.quoted(step.relation.orEmpty())}$title)"
    }

    /** `act("rel", "field" to value, …)` on one line, or one argument a line when one is marked or it is long. */
    private fun act(step: Step, pad: String): List<String> {
        val relation = KotlinText.quoted(step.relation.orEmpty())
        val arguments = bindings.arguments(step)
        reviews += arguments.count { it.review != null }
        val oneLine = "${pad}act(" + (listOf(relation) + arguments.map { "\"${it.field}\" to ${it.expression}" })
            .joinToString(", ") + ")"
        val long = arguments.any { it.review != null } || oneLine.length > WIDTH
        return if (!long) listOf(oneLine) else listOf("${pad}act(", "$pad$INDENT$relation,") + arguments.map {
            "$pad$INDENT\"${it.field}\" to ${it.expression}," + (it.review?.let { why -> " // review: $why" } ?: "")
        } + "$pad)"
    }

    private companion object {
        const val INDENT = "    "
        const val WIDTH = 120
    }
}

/** [value] as one shell word. */
private fun shell(value: String): String = if (value.matches(Regex("[A-Za-z0-9._/:@=+-]+"))) value else
    "'" + value.replace("'", "'\\''") + "'"

/** An input as the capture kept its declaration: required, or with its default or its question. */
private fun declared(name: String, input: Map<*, *>): String {
    val named = listOfNotNull(
        input["default"]?.let { "default = ${KotlinText.quoted(it.toString())}" },
        input["question"]?.let { "question = ${KotlinText.quoted(it.toString())}" },
    )
    return "val $name by input(${named.joinToString(", ")})"
}
